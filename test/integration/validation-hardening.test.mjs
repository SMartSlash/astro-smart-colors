import assert from "node:assert/strict";
import test from "node:test";
import { mkdtemp, mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { generateColorTokens } from "../../src/colors/generate-colors.mjs";
import { getDeclarations, resolveThemeColor } from "../helpers/css-resolver.mjs";

const COLOR = "oklch(.62 .02 32)";
const OVERFLOW = "oklch(.62 .02 1e308turn)";
const PALETTE = `@property --palette-canvas {
  syntax: "<color>";
  inherits: true;
  initial-value: oklch(.96 .01 88);
  role: canvas;
}
@property --palette-ink {
  syntax: "<color>";
  inherits: true;
  initial-value: oklch(.28 .007 4);
  role: ink;
}
@property --palette-primary {
  syntax: "<color>";
  inherits: true;
  initial-value: ${COLOR};
  role: ui;
}`;

async function createProject(t, { config = {}, palette = PALETTE, existingOutputs = false } = {}) {
  const root = await mkdtemp(path.join(tmpdir(), "smart-colors-validation-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(path.join(root, "src"));
  await writeFile(path.join(root, "src/palette.css"), palette);
  await writeFile(path.join(root, "smart-colors.config.mjs"), `export default ${JSON.stringify({
    palette: "src/palette.css",
    output: "generated/theme/colors.css",
    motion: { enabled: true, output: "generated/motion/colors.css" },
    ...config,
  })};\n`);
  await writeFile(path.join(root, "untouched.txt"), "unrelated fixture contents\n");
  if (existingOutputs) {
    for (const output of ["generated/theme/colors.css", "generated/motion/colors.css"]) {
      await mkdir(path.dirname(path.join(root, output)), { recursive: true });
      await writeFile(path.join(root, output), `/* existing ${output} must survive invalid input */\n`);
    }
  }
  return root;
}

async function snapshotProject(root, relativePath = ".", snapshot = {}) {
  const absolutePath = path.join(root, relativePath);
  const info = await stat(absolutePath, { bigint: true });
  snapshot[relativePath] = {
    directory: info.isDirectory(),
    ino: info.ino,
    mtimeNs: info.mtimeNs,
    ctimeNs: info.ctimeNs,
    ...(info.isDirectory() ? {} : { contents: await readFile(absolutePath) }),
  };
  if (info.isDirectory()) {
    for (const entry of (await readdir(absolutePath)).sort()) {
      await snapshotProject(root, path.join(relativePath, entry), snapshot);
    }
  }
  return snapshot;
}

