import { fitToSrgb, oklch } from "./color-math.mjs";
import { createDesignTools } from "./design-recipes.mjs";

// The formatter and the generator share one recipe/knob registry, so the surface
// source quotas and the dark-blend cap cannot drift between the JS model and the
// emitted CSS.
const designTools = createDesignTools();

// A public colour token reads `--color-tune-<token-without--color->-<theme>` with
// the generated value as the fallback: the default stays byte-exact, and a later
// declaration in colors-tuning.css overrides it. The fallback for a fill that
// references `--_color-<id>-dark` keeps the legacy `--color-tune-<id>-dark`
// escape hatch below the more specific per-token override.
function overridePair(name, lightValue, darkValue = lightValue) {
  return `light-dark(var(--color-tune-${name}-light, ${lightValue}), var(--color-tune-${name}-dark, ${darkValue}))`;
}

// A family surface is an aesthetic, non-WCAG mix of the identity and the canvas.
// The knob is the source quota kept in the mix, so a project can retune it at
// runtime without touching an `--_*` internal.
function surfaceExpression(name, variant, theme) {
  const quota = `${name}-${variant}-${theme}-mix`;
  const ratio = mixPercentOf(designTools.surfaceRatio(variant, theme));
  const source = `var(--_color-${name}-${theme === "dark" ? "dark" : "light"})`;
  return `color-mix(in oklch, ${source} var(--color-tune-${quota}, ${ratio}), var(--_color-bg-${theme}))`;
}

function mixPercentOf(ratio) {
  return `${Number((ratio * 100).toFixed(2))}%`;
}

export function formatColorsCss(model, config) {
  const { neutrals, identities, decoratives, logoTokens, onColors, focus, scales } = model;
  const identityNames = Object.keys(identities);
  const decorativeNames = Object.keys(decoratives ?? {});


  return `:root {
  color-scheme: light dark;

  /* ========================================================================
     COLORS — Semantic API generated by @smartslash/astro-smart-colors

     Editable source: ${config.palette}.
     Generated output: ${config.output}.

     Use public tokens below; edit the palette, not this generated file.
     Each identity stays beside its variants, in palette order within its role.
     Pair bg/surface + text, family surface + text, solid/hover + solid-text,
     or a direct fill + its own *-ink companion (not interchangeable).
     Contrast checks cover declared pairs; shortfalls remain warnings.
     Alpha, arbitrary backgrounds and overrides need local checks.
     Advanced options follow the daily API; --_* internals are last.
     ======================================================================== */

  /* ─── Foundation ────────────────────────────────────────────────────────
     Neutral canvas/surface + text/text-muted. Translucent borders are
     ornamental; focus is checked against the neutral backgrounds. */
  --color-bg: ${overridePair("bg", "var(--_color-bg-light)", "var(--_color-bg-dark)")};
  --color-surface: ${overridePair("surface", "var(--_color-surface-light)", "var(--_color-surface-dark)")};
  --color-text: ${overridePair("text", "var(--_color-text-light)", "var(--_color-text-dark)")};
  --color-text-muted: ${overridePair("text-muted", "var(--_color-text-muted-light)", "var(--_color-text-muted-dark)")};

  --color-border-subtle: ${overridePair("border-subtle", "oklch(from var(--color-text) l c h / 14%)")};
  --color-border-strong: ${overridePair("border-strong", "oklch(from var(--color-text) l c h / 28%)")};
  --color-focus-ring: ${overridePair("focus-ring", "var(--_color-focus-ring-light)", "var(--_color-focus-ring-dark)")};
${formatFunctionalFamilies(identities, onColors, "ui", "Identity / brand (ui)")}${formatFunctionalFamilies(identities, onColors, "feedback", "Feedback")}${formatDecorativeSection(decoratives, onColors)}${formatAliases(config.aliases, onColors, identities)}
  /* ─── Controls ──────────────────────────────────────────────────────────
     Active background/border + active-text; focus background + text.
     Opaque state pairs are reported, not silently corrected. Alpha
     boundaries and icons need checks on their actual local background. */
  --color-control-bg: ${overridePair("control-bg", "var(--color-surface)")};
  --color-control-border: ${overridePair("control-border", "var(--color-border-subtle)")};

  --color-control-bg-active: light-dark(
    var(--color-tune-control-bg-active-light, color-mix(in oklch, var(--_color-surface-light) 86%, var(--_color-${config.roles.focus}-light))),
    var(--color-tune-control-bg-active-dark, color-mix(in oklch, var(--_color-surface-dark) 76%, var(--_color-${config.roles.focus}-dark)))
  );

  --color-control-border-active: light-dark(
    var(--color-tune-control-border-active-light, color-mix(in oklch, var(--_color-${config.roles.focus}-light) 46%, var(--_color-text-light))),
    var(--color-tune-control-border-active-dark, color-mix(in oklch, var(--_color-${config.roles.focus}-dark) 46%, var(--_color-text-dark)))
  );

  --color-control-active-text: ${overridePair("control-active-text", "var(--color-text)")};

  --color-control-focus-bg: light-dark(
    var(--color-tune-control-focus-bg-light, color-mix(in oklch, var(--_color-${config.roles.focus}-light) 12%, var(--_color-bg-light))),
    var(--color-tune-control-focus-bg-dark, color-mix(in oklch, var(--_color-${config.roles.focus}-dark) 18%, var(--_color-bg-dark)))
  );

  --color-control-focus-border: ${overridePair("control-focus-border", "oklch(from var(--color-focus-ring) l c h / 72%)")};

  --color-control-icon-muted: light-dark(
    var(--color-tune-control-icon-muted-light, oklch(from var(--_color-text-light) l c h / 48%)),
    var(--color-tune-control-icon-muted-dark, oklch(from var(--_color-text-dark) l c h / 72%))
  );

  /* ─── Advanced ──────────────────────────────────────────────────────────
     Optional composition and refinement; not needed to use color families. */
${formatSurfaceContract()}${formatLogoSection(logoTokens)}${formatScaleSection(scales)}${formatHueVariants(config, identities)}
  /* ─── Native contrast helpers ───────────────────────────────────────────
     Progressive enhancement only; keep on-* companions as the baseline. */
${identityNames.map((name) => `  --ink-${name}: contrast-color(var(--color-${name}));`).join("\n")}

${formatTuningContract(config, neutrals)}

${formatQuickReference(model)}

  /* ─── Internal implementation ───────────────────────────────────────────
     Generated light/dark pairs. Do not consume or override --_* tokens. */
${formatNeutrals(neutrals, config)}

${identityNames.map((name) => formatIdentityInternals(name, identities[name], onColors[name], config)).join("\n\n")}

${decorativeNames.map((name) => formatDecorativeInternals(name, decoratives[name], onColors[name])).join("\n")}

  --_color-focus-ring-light: ${oklch(focus.light)};
  --_color-focus-ring-dark: ${oklch(focus.dark)};
${formatLogoInternals(logoTokens)}}
`;
}

export function formatColorsMotionCss(model) {
  const identityNames = Object.keys(model.identities);
  const decorativeNames = Object.keys(model.decoratives ?? {});
  const functionalSuffixes = ["surface", "surface-strong", "border", "border-strong", "solid", "solid-hover", "solid-text", "text", "text-strong"];
  const colorNames = [...identityNames, ...decorativeNames];
  const registrations = [
    ["--color-bg", "transparent"],
    ["--color-surface", "transparent"],
    ["--color-text", "black"],
    ["--color-text-muted", "black"],
    ["--color-border-subtle", "transparent"],
    ["--color-border-strong", "transparent"],
    ["--color-focus-ring", "black"],
    ...colorNames.flatMap((name) => [
      [`--color-${name}`, "transparent"],
      [`--color-${name}-ink`, "black"],
    ]),
    ...identityNames.flatMap((name) => functionalSuffixes.map((suffix) => [
      `--color-${name}-${suffix}`,
      suffix === "solid-text" || suffix.startsWith("text") ? "black" : "transparent",
    ])),
    ["--surface-color", "transparent"],
    ["--surface-contrast", "black"],
  ];
  const transitionProperties = [
    "--color-surface",
    "--color-text",
    "--color-text-muted",
    "--color-border-subtle",
    "--color-border-strong",
    "--color-focus-ring",
    ...colorNames.flatMap((name) => [`--color-${name}`, `--color-${name}-ink`]),
    ...identityNames.flatMap((name) => functionalSuffixes.map((suffix) => `--color-${name}-${suffix}`)),
  ];

  return `/* Generated by @smartslash/astro-smart-colors.
   Optional motion enhancement: import this file in the consumer's motion layer.
   --color-bg is registered but intentionally not transitioned to avoid browser
   chrome sampling glitches during theme changes. */
${registrations.map(([name, initialValue]) => formatColorProperty(name, initialValue)).join("\n")}

:root {
  transition-property:
${transitionProperties.map((name, index) => `    ${name}${index === transitionProperties.length - 1 ? ";" : ","}`).join("\n")}
  transition-duration: var(--theme-transition-duration, 0.4s);
  transition-timing-function: ease;
}
`;
}

function formatColorProperty(name, initialValue) {
  return `@property ${name} { syntax: "<color>"; inherits: true; initial-value: ${initialValue}; }`;
}

function formatDecorativeSection(decoratives, onColors) {
  const names = Object.keys(decoratives ?? {});
  if (!names.length) return "";

  return `\n  /* ─── Decorative ────────────────────────────────────────────────────\n     Theme-adapted ornamental colors. Canvas contrast is not guaranteed;\n     each color receives a checked, best-effort companion for its own fill.\n     Do not use decorative color alone to communicate meaning or state. */\n${names.map((name) => `  --color-${name}: ${overridePair(name, `var(--_color-${name}-light)`, `var(--_color-${name}-dark)`)};\n  --color-${name}-ink: ${overridePair(`${name}-ink`, onColors[name].light, onColors[name].dark)};`).join("\n")}\n`;
}

function formatTuningContract(config, neutrals) {
  const dark = config.derivation.dark;
  const surface = config.derivation.surface;

  return `  /* ─── Tuning contract ────────────────────────────────────────────────────
     Project-level knobs. Override in colors-tuning.css.

     Family surfaces are aesthetic (non-WCAG) source/background mixes. Retune the
     source quota with --color-tune-<identity>-surface[-strong]-<theme>-mix
     (defaults: 10% / 18% light, 18% / 28% dark). Every public colour also accepts
     a full per-theme override --color-tune-<token-without--color->-<theme>; the
     more specific override wins over a recipe or the legacy per-identity dark
     knob. These runtime overrides are not revalidated by smart-colors check. */
  --color-tune-light-warmth: 100%;
  --color-tune-surface-lightness-shift: ${formatSignedNumber(surface.lightShift)};
  --color-tune-dark-warmth: 100%;
  --color-tune-dark-bg-mix: ${dark.bgMixRatio}%;
  --color-tune-dark-surface-mix: ${dark.surfaceMixRatio}%;
  --color-tune-dark-text-mix: ${formatPercentage(neutrals.textDarkMixRatio ?? dark.textMixRatio)};
  --color-tune-dark-muted-mix: ${formatPercentage(neutrals.textMutedDarkMixRatio ?? 72)};
  --color-tune-elevation-1-shadow-alpha: 10%;
  --color-tune-elevation-1-border-alpha: 28%;
  --color-tune-elevation-1-glow-alpha: 14%;
  --color-tune-elevation-2-shadow-alpha: 13%;
  --color-tune-elevation-2-border-alpha: 36%;
  --color-tune-elevation-2-glow-alpha: 20%;`;
}

function formatNeutrals(neutrals, config) {
  const mode = config.derivation?.dark?.mode ?? "relative";

  if (mode === "relative") {
    // An explicit canvas dark-blend replaces the macro black mix with the shared
    // source/white rule at a constant build-time quota (no runtime knob); the
    // neutral surface follows the chosen canvas, and an explicit canvas or ink
    // resolves the dark text to its solved literal (the readability adjustment
    // cannot be expressed as a static mix). The public --color-tune-bg/surface/
    // text/surface-* overrides remain the runtime escape hatch.
    const canvasBlend = neutrals.canvasBlendMix ?? null;
    const inkBlend = neutrals.inkBlendMix ?? null;
    const quota = canvasBlend ? `${Number(canvasBlend.sourcePercent.toFixed(4))}%` : null;
    const bgDark = canvasBlend
      ? `color-mix(in oklch, var(--_color-bg-source) ${quota}, oklch(1 0 none))`
      : "color-mix(in oklch, var(--_color-bg-warm) var(--color-tune-dark-bg-mix), oklch(0 0 none))";
    const surfaceDark = canvasBlend
      ? `color-mix(in oklch, var(--_color-surface-light) ${quota}, oklch(1 0 none))`
      : "color-mix(in oklch, var(--_color-bg-warm) var(--color-tune-dark-surface-mix), oklch(0 0 none))";
    const textDark = (canvasBlend || inkBlend)
      ? oklch(neutrals.textDark)
      : "color-mix(in oklch, var(--_color-bg-source) var(--color-tune-dark-text-mix), oklch(0.99 0 none))";
    return `  --_color-bg-source: ${oklch(neutrals.bgLight)};
  --_color-bg-neutral: oklch(${neutrals.bgLight.l} 0 none);
  --_color-bg-light: color-mix(in oklch, var(--_color-bg-source) var(--color-tune-light-warmth), var(--_color-bg-neutral));
  --_color-bg-warm: color-mix(in oklch, var(--_color-bg-source) var(--color-tune-dark-warmth), var(--_color-bg-neutral));
  --_color-bg-dark: ${bgDark};

  --_color-surface-light: oklch(from var(--_color-bg-light) clamp(0, calc(l + var(--color-tune-surface-lightness-shift)), 1) c h);
  --_color-surface-dark: ${surfaceDark};

  --_color-text-light: ${oklch(neutrals.textLight)};
  --_color-text-dark: ${textDark};

  --_color-text-muted-light: ${oklch(neutrals.textMutedLight)};
  --_color-text-muted-dark: color-mix(in oklch, var(--_color-text-dark) var(--color-tune-dark-muted-mix), var(--_color-bg-dark));`;
  }

  return `  --_color-bg-light: ${oklch(neutrals.bgLight)};
  --_color-bg-dark: ${oklch(neutrals.bgDark)};

  --_color-surface-light: ${oklch(neutrals.surfaceLight)};
  --_color-surface-dark: ${oklch(neutrals.surfaceDark)};

  --_color-text-light: ${oklch(neutrals.textLight)};
  --_color-text-dark: ${oklch(neutrals.textDark)};

  --_color-text-muted-light: ${oklch(neutrals.textMutedLight)};
  --_color-text-muted-dark: ${oklch(neutrals.textMutedDark)};`;
}

function formatDecorativeInternals(name, color, onColor) {
  return `  --_color-${name}-light: ${oklch(color.light)};
  --_color-${name}-dark: ${oklch(color.dark)};
  --_color-on-${name}-light: ${onColor.light};
  --_color-on-${name}-dark: ${onColor.dark};`;
}

function formatIdentityInternals(name, identity, onColor, config) {
  const mode = config.derivation?.dark?.mode ?? "relative";
  const lines = [
    `  --_color-${name}-source: ${oklch(identity.source)};`,
    `  --_color-${name}-light: ${oklch(identity.light)};`,
  ];

  if (mode === "relative" && identity.mixRatio != null) {
    lines.push(`  --_color-${name}-dark-generated: color-mix(in oklch, var(--_color-${name}-source) var(--color-tune-${name}-dark-mix, ${identity.mixRatio}%), oklch(1 0 none));`);
  } else {
    lines.push(`  --_color-${name}-dark-generated: ${oklch(identity.dark)};`);
  }

  lines.push(`  --_color-${name}-dark: var(--color-tune-${name}-dark, var(--_color-${name}-dark-generated));`);

  if (onColor) {
    lines.push(
      `  --_color-on-${name}-light: ${onColor.light};`,
      `  --_color-on-${name}-dark: ${onColor.dark};`,
    );
  }
  return lines.join("\n");
}

function formatIdentityPublic(name, onColor) {
  const colorToken = `  --color-${name}: ${overridePair(name, `var(--_color-${name}-light)`, `var(--_color-${name}-dark)`)};`;
  const onToken = onColor ? `\n  --color-${name}-ink: ${overridePair(`${name}-ink`, `var(--_color-on-${name}-light)`, `var(--_color-on-${name}-dark)`)};` : "";
  return colorToken + onToken;
}

function formatFunctionalFamilies(identities, onColors, role, heading) {
  const entries = Object.entries(identities ?? {}).filter(([, identity]) => identity.role === role);
  if (!entries.length) return "";

  const definitions = entries.map(([name, identity]) => {
    const light = identity.family.light;
    const dark = identity.family.dark;
    // Border and solid reference the dark identity var. Hover stays resolved
    // so runtime CSS matches the color pair validated by the build-time model.
    const darkVar = `var(--_color-${name}-dark)`;
    // Surfaces are aesthetic (non-WCAG) source/background mixes, so they are the
    // only family variants emitted as a live color-mix() with a runtime source
    // quota. Contrast-adapted variants stay build-time literals: a runtime
    // override would silently invalidate the checked pair.
    const surfaceLight = surfaceExpression(name, "surface", "light");
    const surfaceDark = surfaceExpression(name, "surface", "dark");
    const surfaceStrongLight = surfaceExpression(name, "surface-strong", "light");
    const surfaceStrongDark = surfaceExpression(name, "surface-strong", "dark");
    return `  /* ${name}: ${identity.role} — direct pair, surfaces, text, fills, borders */
${formatIdentityPublic(name, onColors[name])}
  --color-${name}-surface: ${overridePair(`${name}-surface`, surfaceLight, surfaceDark)};
  --color-${name}-surface-strong: ${overridePair(`${name}-surface-strong`, surfaceStrongLight, surfaceStrongDark)};
  --color-${name}-text: ${overridePair(`${name}-text`, oklch(light.text), oklch(dark.text))};
  --color-${name}-text-strong: ${overridePair(`${name}-text-strong`, oklch(light.textStrong), oklch(dark.textStrong))};
  --color-${name}-solid: ${overridePair(`${name}-solid`, oklch(light.solid), darkVar)};
  --color-${name}-solid-hover: ${overridePair(`${name}-solid-hover`, oklch(light.solidHover), oklch(dark.solidHover))};
  --color-${name}-solid-text: ${overridePair(`${name}-solid-text`, oklch(light.onSolid), oklch(dark.onSolid))};
  --color-${name}-border: ${overridePair(`${name}-border`, oklch(light.border), darkVar)};
  --color-${name}-border-strong: ${overridePair(`${name}-border-strong`, oklch(light.borderStrong), oklch(dark.borderStrong))};`;
  });

  return `\n  /* ─── ${heading} ───────────────────────────────────────────────────
     Stable designer API. Text/border-strong are checked on declared surfaces;
     solid-text is checked on solid + hover with warnings for shortfalls.
     Identity dark tuning changes border/solid, not hover or foregrounds;
     overrides need local checks. Numeric scales are optional advanced tokens. */
${definitions.join("\n\n")}\n`;
}

function formatSurfaceContract() {
  return `

  /* ─── Surface contract ───────────────────────────────────────────────────
     Root-level substrate, not an automatic local theme scope. An inherited
     root formula does not re-resolve after a child changes --surface-color;
     local surfaces need an explicit foreground pair and local derivations. */
  --surface-color: var(--color-bg);
  --surface-contrast: contrast-color(var(--surface-color));
  --surface-text: var(--color-text);
  --surface-text-muted: var(--color-text-muted);
  --surface-border: var(--color-border-subtle);

  /* ─── Elevation ──────────────────────────────────────────────────────────
     Light scheme uses soft shadows. Dark scheme swaps to tinted glow/border
     derived from the active --surface-color. */
  --elevation-1:
    0 1px 2px light-dark(color-mix(in oklch, var(--surface-contrast) var(--color-tune-elevation-1-shadow-alpha), transparent), transparent),
    0 8px 24px light-dark(color-mix(in oklch, var(--surface-contrast) var(--color-tune-elevation-1-shadow-alpha), transparent), transparent),
    inset 0 0 0 1px light-dark(transparent, oklch(from var(--surface-color) calc(l + 0.34) c h / var(--color-tune-elevation-1-border-alpha))),
    0 0 18px light-dark(transparent, oklch(from var(--surface-color) calc(l + 0.30) c h / var(--color-tune-elevation-1-glow-alpha)));

  --elevation-2:
    0 2px 6px light-dark(color-mix(in oklch, var(--surface-contrast) var(--color-tune-elevation-2-shadow-alpha), transparent), transparent),
    0 18px 48px light-dark(color-mix(in oklch, var(--surface-contrast) var(--color-tune-elevation-2-shadow-alpha), transparent), transparent),
    inset 0 0 0 1px light-dark(transparent, oklch(from var(--surface-color) calc(l + 0.40) c h / var(--color-tune-elevation-2-border-alpha))),
    0 0 26px light-dark(transparent, oklch(from var(--surface-color) calc(l + 0.36) c h / var(--color-tune-elevation-2-glow-alpha)));

  /* Filter equivalents for clipped, masked or alpha-shaped surfaces.
     drop-shadow() uses Gaussian standard deviation, mapped here to half of the
     corresponding box-shadow blur radius; inset borders remain surface-owned. */
  --elevation-filter-1:
    drop-shadow(0 1px 1px light-dark(color-mix(in oklch, var(--surface-contrast) var(--color-tune-elevation-1-shadow-alpha), transparent), transparent))
    drop-shadow(0 8px 12px light-dark(color-mix(in oklch, var(--surface-contrast) var(--color-tune-elevation-1-shadow-alpha), transparent), transparent))
    drop-shadow(0 0 9px light-dark(transparent, oklch(from var(--surface-color) calc(l + 0.30) c h / var(--color-tune-elevation-1-glow-alpha))));

  --elevation-filter-2:
    drop-shadow(0 2px 3px light-dark(color-mix(in oklch, var(--surface-contrast) var(--color-tune-elevation-2-shadow-alpha), transparent), transparent))
    drop-shadow(0 18px 24px light-dark(color-mix(in oklch, var(--surface-contrast) var(--color-tune-elevation-2-shadow-alpha), transparent), transparent))
    drop-shadow(0 0 13px light-dark(transparent, oklch(from var(--surface-color) calc(l + 0.36) c h / var(--color-tune-elevation-2-glow-alpha))));`;
  }

function formatScaleSection(scales) {
  const entries = Object.entries(scales ?? {});
  if (!entries.length) return "";

  return `
  /* ─── Optional numeric tonal steps ────────────────────────────────────────
     Advanced tuning API. Functional components should prefer the validated
     surface / border / solid / solid-text / text family above. */
${entries.map(([name, scale]) => formatScale(name, scale)).join("\n")}
`;
}

function formatSignedNumber(value) {
  return Number(value.toFixed(4)).toString();
}

function formatPercentage(value) {
  return `${Number(value.toFixed(2))}%`;
}

function formatScale(name, scale) {
  const lightSteps = Object.entries(scale.light).sort(([a], [b]) => Number(a) - Number(b));
  return lightSteps
    .map(([step, color]) => {
      const darkColor = scale.dark[step];
      return `  --color-${name}-${step}: ${overridePair(`${name}-${step}`, oklch(color), oklch(darkColor))};`;
    })
    .join("\n");
}

function formatAliases(aliases, onColors, identities) {
  const entries = Object.entries(aliases ?? {}).filter(([, target]) => Object.hasOwn(onColors, target));
  if (!entries.length) return "\n";
  const functionalSuffixes = ["surface", "surface-strong", "text", "text-strong", "solid", "solid-hover", "solid-text", "border", "border-strong"];

  return `\n  /* ─── Aliases ───────────────────────────────────────────────────────────
     Alternative names for existing colors, not additional palette choices. */
${entries
    .map(([alias, target]) => {
      // The alias references its target's resolved per-theme value and keeps its
      // own per-theme override on top, so mapping and precedence both hold.
      const targetToken = `var(--color-${target})`;
      const lines = [`  /* ${alias} → ${target} */`, `  --color-${alias}: ${overridePair(alias, targetToken)};`];
      if (Object.hasOwn(onColors, target)) lines.push(`  --color-${alias}-ink: ${overridePair(`${alias}-ink`, `var(--color-${target}-ink)`)};`);
      if (Object.hasOwn(identities, target)) {
        for (const suffix of functionalSuffixes) {
          lines.push(`  --color-${alias}-${suffix}: ${overridePair(`${alias}-${suffix}`, `var(--color-${target}-${suffix})`)};`);
        }
      }
      return lines.join("\n");
    })
    .join("\n")}\n`;
}

function formatLogoSection(logoTokens) {
  const names = Object.keys(logoTokens ?? {});
  if (!names.length) return "";

  let css = "\n  /* ─── Logo / brand ──────────────────────────────────────────────────\n";
  css += "     Source colors from smart-colors.config.mjs.\n";
  css += "     Dark variants generated at build time. */\n";

  for (const name of names) {
    css += `  --logo-${name}: light-dark(var(--_logo-${name}-light), var(--_logo-${name}-dark));\n`;
  }

  if (logoTokens.accent) {
    css += "  --logo-accent-alpha: oklch(from var(--logo-accent) l c h / 88%);\n";
  }

  css += "  --logo-stroke: light-dark(oklch(0.99 0 0), var(--color-bg));\n";
  css += "  --logo-bg-fill: light-dark(var(--color-bg), var(--color-surface));\n";

  return css;
}

function formatLogoInternals(logoTokens) {
  const entries = Object.entries(logoTokens ?? {});
  if (!entries.length) return "";

  return `\n${entries.map(([name, colors]) => `  --_logo-${name}-light: ${oklch(colors.light)};\n  --_logo-${name}-dark: ${oklch(colors.dark)};`).join("\n")}\n`;
}

function formatHueVariants(config, identities) {
  const hv = config.scales?.hueVariants;
  if (!hv?.enabled || !hv.shifts?.length || !hv.applyTo?.length) return "";

  let css = "\n  /* ─── Hue variants (generated at build time) ───────────────────────────── */\n";

  for (const name of hv.applyTo) {
    const identity = identities[name];
    if (!identity) continue;

    const variants = hv.shifts.map((shift) => ({
      shift,
      color: fitToSrgb({ ...identity.light, h: identity.light.h + shift }),
      darkColor: fitToSrgb({ ...identity.dark, h: identity.dark.h + shift }),
    }));

    if (variants.length === 2) {
      const [warm, cool] = sortHueTemperatureVariants(variants);
      css += `  --color-${name}-warm: ${overridePair(`${name}-warm`, oklch(warm.color), oklch(warm.darkColor))};\n`;
      css += `  --color-${name}-cool: ${overridePair(`${name}-cool`, oklch(cool.color), oklch(cool.darkColor))};\n`;
      continue;
    }

    for (const variant of variants) {
      const direction = variant.shift >= 0 ? "plus" : "minus";
      const amount = Math.abs(variant.shift);
      css += `  --color-${name}-hue-${direction}-${amount}: ${overridePair(`${name}-hue-${direction}-${amount}`, oklch(variant.color), oklch(variant.darkColor))};\n`;
    }
  }

  return css;
}

function sortHueTemperatureVariants(variants) {
  const coolHue = 240;
  const sortedByCoolDistance = [...variants].sort((a, b) => {
    return hueDistance(a.color.h, coolHue) - hueDistance(b.color.h, coolHue);
  });
  const cool = sortedByCoolDistance[0];
  const warm = sortedByCoolDistance[1];
  return [warm, cool];
}

function hueDistance(a, b) {
  const diff = Math.abs((((a - b) % 360) + 360) % 360);
  return Math.min(diff, 360 - diff);
}

function formatQuickReference(model) {
  const { neutrals, identities } = model;
  const identityNames = Object.keys(identities);

  let ref = `  /* ─── Quick reference (resolved at generation time) ──────────────────────
     Values before project overrides from colors-tuning.css.
     Format: L C H  (oklch components).

     Token                    Light               Dark`;

  const rows = [
    ["--color-bg", neutrals.bgLight, neutrals.bgDark],
    ["--color-surface", neutrals.surfaceLight, neutrals.surfaceDark],
    ["--color-text", neutrals.textLight, neutrals.textDark],
    ["--color-text-muted", neutrals.textMutedLight, neutrals.textMutedDark],
    ...identityNames.map((name) => [
      `--color-${name}`,
      identities[name].light,
      identities[name].dark,
    ]),
  ];

  for (const [name, light, dark] of rows) {
    const pad = Math.max(1, 25 - name.length);
    ref += `\n     ${name}${' '.repeat(pad)}${shortOklchStr(light)}      ${shortOklchStr(dark)}`;
  }

  ref += `\n
     Functional API:  --color-*-surface / --solid / --border / --text
     Elevation:     --elevation-1/2 / --elevation-filter-1/2
     Surface:       --surface-color / --surface-contrast / --surface-text
     Controls:      --color-control-*
     Tuning:        --color-tune-* (override in colors-tuning.css)
     ======================================================================== */`;
  return ref;
}

function shortOklchStr(color) {
  return `${color.l.toFixed(3)} ${color.c.toFixed(3)} ${Math.round(color.h)}`;
}
