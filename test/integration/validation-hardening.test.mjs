const LEGACY_PALETTE = `:root {
  /* @role canvas */
  --palette-canvas: oklch(.96 .01 88);
  /* @role ink */
  --palette-ink: oklch(.28 .007 4);
  /* @role ui */
  --palette-primary: ${COLOR};
}`;

function assertFiniteUniqueOutput(report) {
  assert.deepEqual(report.errors, []);
  for (const css of [report.css, report.motionCss]) {
    assert.equal(typeof css, "string");
    assert.doesNotMatch(css, /NaN|Infinity|undefined/);
  }
  const entries = [...report.css.matchAll(/^\s*(--[a-z0-9_-]+):\s*([^;]+);/gm)]
    .map(([, name, value]) => [name, value.trim()]);
  assert.ok(entries.length > 0);
  const declarations = new Map(entries);
  assert.equal(declarations.size, entries.length, "color declarations must be unique");
  const registrations = [...report.motionCss.matchAll(/@property\s+(--[a-z0-9_-]+)\s*\{/g)]
    .map(([, name]) => name);
  assert.ok(registrations.length > 0);
  assert.equal(new Set(registrations).size, registrations.length, "motion registrations must be unique");
  return declarations;
}

function publicColorNames(declarations, name) {
  return [...declarations.keys()].filter((token) =>
    token === `--color-${name}` || token === `--color-${name}-ink` || token.startsWith(`--color-${name}-`)).sort();
}

test("legacy UI constructor declaration uses the default dark blend, not inherited metadata", async (t) => {
  const root = await createProject(t, {
    palette: LEGACY_PALETTE.replace(`--palette-primary: ${COLOR};`, "--constructor: oklch(.62 .16 32);"),
    config: { aliases: { brand: "constructor" } },
  });
  const report = await generateColorTokens({ root, suggest: false });
  const declarations = assertFiniteUniqueOutput(report);

  assert.equal(Object.hasOwn(report.config.roles.identities, "constructor"), true);
  assert.deepEqual(report.config.roles.identities.constructor, { token: "--constructor", role: "ui" });
  assert.equal(report.config.roles.focus, "constructor");
  assert.equal(declarations.get("--_color-constructor-source"), "oklch(0.62 0.16 32)");
  assert.equal(declarations.get("--_color-constructor-dark-generated"),
    "color-mix(in oklch, var(--_color-constructor-source) var(--color-tune-constructor-dark-mix, 81%), oklch(1 0 none))");
  // The public pair resolves to its internals and exposes its own per-theme override.
  const semantic = getDeclarations(report.css);
  for (const scheme of ["light", "dark"]) {
    assert.deepEqual(resolveThemeColor(semantic, "--color-constructor", scheme), resolveThemeColor(semantic, `--_color-constructor-${scheme}`, scheme), `--color-constructor ${scheme}`);
    assert.deepEqual(resolveThemeColor(semantic, "--color-constructor-ink", scheme), resolveThemeColor(semantic, `--_color-on-constructor-${scheme}`, scheme), `--color-constructor-ink ${scheme}`);
  }
  const baseOverride = new Map(semantic);
  baseOverride.set("--color-tune-constructor-dark", "oklch(0.3 0.04 10)");
  assert.deepEqual(resolveThemeColor(baseOverride, "--color-constructor", "dark"), { l: 0.3, c: 0.04, h: 10 });
  // The alias maps to its target in every theme and keeps its own override on top.
  for (const suffix of ["", "-ink", "-surface", "-surface-strong", "-text", "-text-strong", "-solid", "-solid-hover", "-solid-text", "-border", "-border-strong"]) {
    assert.equal(semantic.has(`--color-constructor${suffix}`), true);
    assert.equal(semantic.has(`--color-brand${suffix}`), true);
    for (const scheme of ["light", "dark"]) {
      assert.deepEqual(resolveThemeColor(semantic, `--color-brand${suffix}`, scheme), resolveThemeColor(semantic, `--color-constructor${suffix}`, scheme), `brand${suffix}→constructor${suffix} ${scheme}`);
    }
  }
  const aliasOverride = new Map(semantic);
  aliasOverride.set("--color-tune-brand-surface-dark", "oklch(0.2 0.05 300)");
  assert.deepEqual(resolveThemeColor(aliasOverride, "--color-brand-surface", "dark"), { l: 0.2, c: 0.05, h: 300 });
  assert.deepEqual(resolveThemeColor(aliasOverride, "--color-constructor-surface", "dark"), resolveThemeColor(semantic, "--color-constructor-surface", "dark"));
});

test("missing optional constructor token skips its decorative color and alias", async (t) => {
  const root = await createProject(t, {
    palette: LEGACY_PALETTE,
    config: {
      roles: { decoratives: { constructor: { token: "--constructor", role: "decorative" } } },
      aliases: { brand: "constructor" },
    },
  });
  const report = await generateColorTokens({ root, suggest: false });
  const declarations = assertFiniteUniqueOutput(report);

  assert.ok(report.warnings.some((warning) =>
    warning.includes("Missing decorative palette tokens skipped: --constructor (roles.decoratives.constructor)")));
  assert.deepEqual(publicColorNames(declarations, "constructor"), []);
  assert.deepEqual(publicColorNames(declarations, "brand"), []);
  for (const css of [report.css, report.motionCss]) {
    assert.doesNotMatch(css, /--(?:_?color)-(?:on-)?(?:constructor|brand)\b/);
  }
});

test("declared decorative constructor emits its pair and alias without phantom functional families", async (t) => {
  const root = await createProject(t, {
    palette: LEGACY_PALETTE.replace("\n}", "\n  /* @role decorative */\n  --constructor: oklch(.62 .16 32);\n}"),
    config: { aliases: { brand: "constructor" } },
  });
  const report = await generateColorTokens({ root, suggest: false });
  const declarations = assertFiniteUniqueOutput(report);

  assert.equal(Object.hasOwn(report.config.roles.decoratives, "constructor"), true);
  assert.deepEqual(report.config.roles.decoratives.constructor, { token: "--constructor", role: "decorative" });
  assert.equal(Object.hasOwn(report.config.roles.identities, "constructor"), false);
  assert.deepEqual(publicColorNames(declarations, "constructor"), ["--color-constructor", "--color-constructor-ink"]);
  assert.deepEqual(publicColorNames(declarations, "brand"), ["--color-brand", "--color-brand-ink"]);
  // The decorative pair resolves to its internals; the alias maps to it; both keep a per-theme override.
  const semantic = getDeclarations(report.css);
  for (const scheme of ["light", "dark"]) {
    assert.deepEqual(resolveThemeColor(semantic, "--color-constructor", scheme), resolveThemeColor(semantic, `--_color-constructor-${scheme}`, scheme), `decorative ${scheme}`);
    assert.deepEqual(resolveThemeColor(semantic, "--color-brand", scheme), resolveThemeColor(semantic, "--color-constructor", scheme), `alias ${scheme}`);
    assert.deepEqual(resolveThemeColor(semantic, "--color-brand-ink", scheme), resolveThemeColor(semantic, "--color-constructor-ink", scheme), `alias ink ${scheme}`);
  }
  const tuned = new Map(semantic);
  tuned.set("--color-tune-constructor-dark", "oklch(0.2 0.05 300)");
  assert.deepEqual(resolveThemeColor(tuned, "--color-constructor", "dark"), { l: 0.2, c: 0.05, h: 300 });
  tuned.set("--color-tune-brand-dark", "oklch(0.4 0.06 200)");
  assert.deepEqual(resolveThemeColor(tuned, "--color-brand", "dark"), { l: 0.4, c: 0.06, h: 200 });
  assert.equal(report.warnings.some((warning) => warning.includes("Missing decorative")), false);
});

test("valid logo emission remains collision-free without reserving unused names", async (t) => {
  for (const [name, logo, expectedNames] of [
    ["accent-alpha alone", { enabled: true, sources: { "accent-alpha": COLOR } }, ["accent-alpha", "stroke", "bg-fill"]],
    ["accent companion", { enabled: true, sources: { accent: COLOR } }, ["accent", "accent-alpha", "stroke", "bg-fill"]],
    ["empty logo", { enabled: true, sources: {} }, []],
    ["disabled logo", { enabled: false, sources: { stroke: COLOR, "bg-fill": COLOR, accent: COLOR, "accent-alpha": COLOR } }, []],
  ]) {
    await t.test(name, async (t) => {
      const root = await createProject(t, { config: { logo } });
      const report = await generateColorTokens({ root, suggest: false });
      const names = [...report.css.matchAll(/^\s*--logo-([a-z0-9-]+):/gm)].map((match) => match[1]);
      assert.deepEqual(names.sort(), [...expectedNames].sort());
      assert.equal(new Set(names).size, names.length);
      assert.doesNotMatch(report.css, /NaN|Infinity/);
      assert.equal(await readFile(path.join(root, "generated/theme/colors.css"), "utf8"), report.css);
      assert.equal(await readFile(path.join(root, "generated/motion/colors.css"), "utf8"), report.motionCss);
      const beforeCheck = await snapshotProject(root);
      const checked = await generateColorTokens({ root, check: true, suggest: false });
      assert.deepEqual(checked.errors, []);
      assert.equal(checked.changed, false);
      assert.deepEqual(await snapshotProject(root), beforeCheck);
    });
  }
});
