import { oklch } from "./color-math.mjs";

export function formatColorsCss(model, config) {
  const { neutrals, identities, decoratives, onColors, focus, scales } = model;
  const identityNames = Object.keys(identities);
  const decorativeNames = Object.keys(decoratives ?? {});
  const generatedLogoCss = config.logo.enabled && config.logo.css.trim()
    ? `\n  /* ─── Logo / brand contract ─────────────────────────────────────────────\n     Optional project-specific CSS injected from smart-colors.config.mjs. */\n${indentCss(config.logo.css.trim(), 2)}\n`
    : "";

  return `:root {
  color-scheme: light dark;

  /* ========================================================================
     COLORS — Semantic API generated by @smartslash/astro-smart-colors

     Editable source: ${config.palette}.
     Generated output: ${config.output}.

     Contract:
     - components consume public \`--color-*\` tokens only;
     - \`--_*\` tokens are generated implementation details;
     - aliases such as \`--color-accent\` map to configured identity roles;
     - \`--color-on-*\` pairs target WCAG AA for text/icons on identity
       backgrounds;
     - identities without an on-color (e.g. decorative role) skip the pair;
     - optional logo/brand tokens are project-specific.
     ======================================================================== */

  /* ─── Internal light/dark pairs ───────────────────────────────────────── */
  --_color-bg-light: ${oklch(neutrals.bgLight)};
  --_color-bg-dark: ${oklch(neutrals.bgDark)};

  --_color-surface-light: ${oklch(neutrals.surfaceLight)};
  --_color-surface-dark: ${oklch(neutrals.surfaceDark)};

  --_color-text-light: ${oklch(neutrals.textLight)};
  --_color-text-dark: ${oklch(neutrals.textDark)};

  --_color-text-muted-light: ${oklch(neutrals.textMutedLight)};
  --_color-text-muted-dark: ${oklch(neutrals.textMutedDark)};

${identityNames.map((name) => formatIdentityInternals(name, identities[name], onColors[name])).join("\n\n")}
${decorativeNames.map((name) => formatDecorativeInternals(name, decoratives[name])).join("\n")}

  --_color-focus-ring-light: ${oklch(focus.light)};
  --_color-focus-ring-dark: ${oklch(focus.dark)};

  /* ─── Public semantic API ─────────────────────────────────────────────── */
  --color-bg: light-dark(var(--_color-bg-light), var(--_color-bg-dark));
  --color-surface: light-dark(var(--_color-surface-light), var(--_color-surface-dark));
  --color-text: light-dark(var(--_color-text-light), var(--_color-text-dark));
  --color-text-muted: light-dark(var(--_color-text-muted-light), var(--_color-text-muted-dark));

${identityNames.map((name) => formatIdentityPublic(name, onColors[name])).join("\n")}
${formatDecorativeSection(decoratives)}
${formatAliases(config.aliases, onColors)}
  --color-border-subtle: color-mix(in oklch, var(--color-text) 14%, transparent);
  --color-border-strong: color-mix(in oklch, var(--color-text) 28%, transparent);
  --color-focus-ring: light-dark(var(--_color-focus-ring-light), var(--_color-focus-ring-dark));
${generatedLogoCss}${Object.keys(scales).length ? `\n  /* ─── Color scales (generated when scales.enabled = true) ──────────────── */\n${Object.entries(scales).map(([name, scale]) => formatScale(name, scale)).join("\n")}\n` : ""}
  /* ─── Controls ────────────────────────────────────────────────────────── */
  --color-control-bg: var(--color-surface);
  --color-control-border: var(--color-border-subtle);

  --color-control-bg-active: light-dark(
    color-mix(in oklch, var(--_color-surface-light) 86%, var(--_color-${config.roles.focus}-light)),
    color-mix(in oklch, var(--_color-surface-dark) 76%, var(--_color-${config.roles.focus}-dark))
  );

  --color-control-border-active: light-dark(
    color-mix(in oklch, var(--_color-${config.roles.focus}-light) 46%, var(--_color-text-light)),
    color-mix(in oklch, var(--_color-${config.roles.focus}-dark) 46%, var(--_color-text-dark))
  );

  --color-control-active-text: var(--color-text);

  --color-control-focus-bg: light-dark(
    color-mix(in oklch, var(--_color-${config.roles.focus}-light) 12%, var(--_color-bg-light)),
    color-mix(in oklch, var(--_color-${config.roles.focus}-dark) 18%, var(--_color-bg-dark))
  );

  --color-control-focus-border: color-mix(in oklch, var(--color-focus-ring) 72%, transparent);

  --color-control-icon-muted: light-dark(
    color-mix(in oklch, var(--_color-text-light) 48%, transparent),
    color-mix(in oklch, var(--_color-text-dark) 72%, transparent)
  );
}
`;
}

function formatDecorativeSection(decoratives) {
  const names = Object.keys(decoratives ?? {});
  if (!names.length) return "";

  return `\n  /* ─── Decorative ────────────────────────────────────────────────────\n     Colors preserved as authored. No contrast correction.\n     For gradients, shadows, ornamental accents, visual detail.\n     Do not use for body text or critical UI text. */\n${names.map((name) => `  --color-${name}: light-dark(var(--_color-${name}-light), var(--_color-${name}-dark));`).join("\n")}\n`;
}

function formatDecorativeInternals(name, color) {
  return `  --_color-${name}-light: ${oklch(color.light)};\n  --_color-${name}-dark: ${oklch(color.dark)};`;
}

function formatIdentityInternals(name, identity, onColor) {
  const lines = [
    `  --_color-${name}-light: ${oklch(identity.light)};`,
    `  --_color-${name}-dark: ${oklch(identity.dark)};`,
  ];
  if (onColor) {
    lines.push(
      `  --_color-on-${name}-light: ${onColor.light};`,
      `  --_color-on-${name}-dark: ${onColor.dark};`,
    );
  }
  return lines.join("\n");
}

function formatIdentityPublic(name, onColor) {
  if (onColor) {
    return `  --color-${name}: light-dark(var(--_color-${name}-light), var(--_color-${name}-dark));
  --color-on-${name}: light-dark(var(--_color-on-${name}-light), var(--_color-on-${name}-dark));`;
  }
  return `  --color-${name}: light-dark(var(--_color-${name}-light), var(--_color-${name}-dark));`;
}

function formatScale(name, scale) {
  const lightSteps = Object.entries(scale.light).sort(([a], [b]) => Number(a) - Number(b));
  return lightSteps
    .map(([step, color]) => {
      const darkColor = scale.dark[step];
      return `  --color-${name}-${step}: light-dark(${oklch(color)}, ${oklch(darkColor)});`;
    })
    .join("\n");
}

function formatAliases(aliases, onColors) {
  const entries = Object.entries(aliases ?? {});
  if (!entries.length) return "\n";

  return `\n${entries
    .map(([alias, target]) => {
      if (onColors[target]) {
        return `  --color-${alias}: var(--color-${target});\n  --color-on-${alias}: var(--color-on-${target});`;
      }
      return `  --color-${alias}: var(--color-${target});`;
    })
    .join("\n")}\n`;
}

function indentCss(css, spaces) {
  const pad = " ".repeat(spaces);
  return css
    .split("\n")
    .map((line) => `${pad}${line}`)
    .join("\n");
}
